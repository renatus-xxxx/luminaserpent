#!/usr/bin/env python3
"""Generate the baked title art for the MSX build:
- src/title_img.h : the B-design logo (cyan outline letters with a
  pink beam through LUMINA), flat indices, PackBits rows - replaces
  the old photograph-derived logo that read as blurred.
- data/tpl8.dat / data/gpl8.dat: two realistic Earth discs (title +
  in-game), rendered with continents / clouds / terminator shading,
  quantized to GRB332 (see write_planets8 below).
Usage: python3 tools/gen_title_art.py
"""
import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageFilter, ImageChops

BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# game palette GRB333 -> 8-bit rgb (must match gen_title_image.py)
PALETTE = [
    (0, 0, 0), (0, 0, 1), (0, 1, 3), (2, 0, 4), (0, 2, 5), (0, 4, 7),
    (1, 5, 2), (0, 6, 7), (3, 6, 7), (2, 7, 2), (7, 6, 0), (7, 3, 0),
    (7, 0, 0), (7, 2, 5), (7, 7, 7), (0, 6, 7),
]
PAL8 = np.array([(r * 36, g * 36, b * 36) for (r, g, b) in PALETTE],
                dtype=np.float32)


def packbits_row(data):
    out = []
    i, n = 0, len(data)
    while i < n:
        run = 1
        while i + run < n and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            out += [257 - run, data[i]]
            i += run
        else:
            start = i
            i += run
            while i < n:
                r = 1
                while i + r < n and data[i + r] == data[i] and r < 3:
                    r += 1
                if r >= 3:
                    break
                i += 1
                if i - start >= 128:
                    break
            lit = data[start:i]
            out.append(len(lit) - 1)
            out += lit
    return out


def emit_header(path, guard, name, idx, x, y, extra_note=""):
    h, w = idx.shape
    rows = []
    total = 0
    for yy in range(h):
        row = []
        for xx in range(0, w, 2):
            row.append((int(idx[yy, xx]) << 4) | int(idx[yy, xx + 1]))
        packed = packbits_row(row)
        rows.append(packed)
        total += len(packed)
    return rows, total


def write_logo():
    W, H = 240, 72
    idx = np.ones((H, W), dtype=np.uint8)  # bg = 1

    def word_mask(word, target_w):
        px = 120
        f = ImageFont.truetype(BOLD, px)
        tmp = Image.new('L', (900, 220), 0)
        ImageDraw.Draw(tmp).text((10, 10), word, font=f, fill=255)
        m = tmp.crop(tmp.getbbox())
        scale = target_w / m.width
        m = m.resize((target_w, max(4, int(m.height * scale))),
                     Image.LANCZOS)
        return m.point(lambda v: 255 if v > 110 else 0)

    def outline_of(m):
        inner = m
        for _ in range(2):
            inner = inner.filter(ImageFilter.MinFilter(3))
        return ImageChops.subtract(m, inner)

    lum = word_mask("LUMINA", 208)
    ser = word_mask("SERPENT", 232)
    for mask, y in ((lum, 3), (ser, 37)):
        o = outline_of(mask)
        x = (W - o.width) // 2
        sub = idx[y:y + o.height, x:x + o.width]
        om = np.asarray(o) > 0
        sub[om] = 7
        idx[y:y + o.height, x:x + o.width] = sub
    # the beam through LUMINA's middle: white core + pink underlay
    beam_y = 3 + lum.height // 2
    idx[beam_y + 1, :] = 13
    idx[beam_y, :] = 14
    # The logo ships as a 1bpp mask of the outline (idx 7): the
    # full-colour bake (5,117 B) pushed the .COM past the DOS
    # memory ceiling (BSS end must stay below ~0xC838; see the
    # v1.8 size bisect). The mask packs to ~2 KB and the beam
    # (two solid rows) is drawn by the game code itself.
    mask_rows = []
    total = 0
    for yy in range(H):
        by = []
        for i in range(0, W, 8):
            v = 0
            for j in range(8):
                if idx[yy, i + j] == 7:
                    v |= (0x80 >> j)
            by.append(v)
        pk = packbits_row(by)
        mask_rows.append(pk)
        total += len(pk)
    with open("src/title_img.h", "w") as f:
        f.write("/* generated by tools/gen_title_art.py - do not edit */\n")
        f.write("#ifndef TITLE_IMG_H\n#define TITLE_IMG_H\n\n")
        f.write("#define TLOGO_X 8\n#define TLOGO_Y 26\n")
        f.write(f"#define TLOGO_W {W}\n#define TLOGO_H {H}\n")
        f.write(f"#define TLOGO_WB {W // 2}\n")
        f.write(f"#define TLOGO_BEAM_Y {beam_y}\n")
        f.write("static const unsigned char tlogo_mask[] = {\n")
        for packed in mask_rows:
            f.write("  " + ",".join(str(b) for b in packed) + ",\n")
        f.write("};\n\n#endif\n")
    print(f"logo {W}x{H} mask packed={total}")
    Image.fromarray(PAL8[idx].astype(np.uint8)).resize(
        (W * 2, H * 2), Image.NEAREST).save("design/logo_title_preview.png")


# ---------------- Earth rendering ----------------

def _noise(w, h, cw, chh, seed):
    rng = np.random.RandomState(seed)
    g = rng.rand(chh, cw).astype(np.float32)
    im = Image.fromarray((g * 255).astype(np.uint8)).resize(
        (w, h), Image.BILINEAR)
    return np.asarray(im, dtype=np.float32) / 255.0


def _fractal(w, h, seed):
    n = np.zeros((h, w), np.float32)
    for cells, amp in ((4, 0.5), (8, 0.25), (16, 0.15), (32, 0.07),
                       (64, 0.03)):
        n += _noise(w, h, cells, cells, seed + cells) * amp
    return n / n.max()


def earth_rgb(w, h, ccx, ccy, r, seed=23):
    """RGB float image of the disc inside a wxh rect (disc centre at
    rect coords ccx,ccy); alpha channel = disc coverage incl. glow."""
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    nx = (xx - ccx) / r
    ny = (yy - ccy) / r
    d2 = nx * nx + ny * ny
    inside = d2 < 1.0
    nz = np.sqrt(np.clip(1 - d2, 0, 1))
    lx, ly = -0.55, -0.75
    lz = np.sqrt(max(0.0, 1 - lx * lx - ly * ly))
    diff = np.clip(nx * lx + ny * ly + nz * lz, 0, 1)
    shade = 0.12 + 0.88 * np.power(diff, 0.75)
    cont = _fractal(w, h, seed)
    landm = cont > 0.57
    oc = np.zeros((h, w, 3), np.float32)
    oc[..., 0] = 8 + 20 * diff
    oc[..., 1] = 60 + 90 * diff
    oc[..., 2] = 130 + 110 * diff
    dry = _fractal(w, h, seed + 99)
    ld = np.zeros((h, w, 3), np.float32)
    ld[..., 0] = 40 + 120 * dry
    ld[..., 1] = 95 + 70 * dry
    ld[..., 2] = 35 + 40 * dry
    surf = np.where(landm[..., None], ld, oc)
    ice = (np.abs(ny + 0.25 * _noise(w, h, 8, 8, seed + 5)) > 0.82) & inside
    surf[ice] = (225, 240, 250)
    surf *= shade[..., None]
    spec = np.power(diff, 18) * (~landm) * 60
    surf += spec[..., None] * np.array([0.5, 0.8, 1.0], np.float32)
    cl = _fractal(w, h, 21)
    sw = np.clip((cl - 0.52) * 2.6, 0, 1) * (0.25 + 0.75 * diff)
    surf = surf * (1 - sw[..., None] * 0.75) + \
        np.array([235, 245, 255], np.float32) * (sw[..., None] * 0.75)
    rim = np.clip((d2 - 0.90) * 14, 0, 1) * inside * (0.3 + 0.7 * diff)
    surf += rim[..., None] * np.array([40, 110, 160], np.float32)
    glow = np.clip(1 - (np.sqrt(d2) - 1.0) * 9, 0, 1) * (d2 >= 1.0) * \
        (0.25 + 0.75 * np.clip(diff + 0.35, 0, 1))
    rgb = surf + glow[..., None] * np.array([30, 90, 150], np.float32)
    cover = inside | (glow > 0.03)
    return rgb, cover


# ---------------- SCREEN 8 (GRB332) planet data ----------------
# The game streams the two Earths from disk files: the
# .COM is at the DOS memory ceiling, so the images ship as
# data/tpl8.dat / data/gpl8.dat (PackBits byte rows, no header;
# geometry comes from the TPL_/GPL_ macros in src/main.c). Colours
# are GRB332, quantized "fsdisc" style (user decision, 2026-10-27):
# Floyd-Steinberg error diffusion inside the planet disc + glow
# only, flat quantization outside it - full-frame dithering made
# the backdrop noisy and broke the seam against the procedural
# background, while flat-only quantization banded the smoothly
# shaded Earth. The rects' corners quantize to exactly the GRB332
# bytes the runtime slice renderer paints for the Deep Field
# background (spec: tools/gen_deepfield.py - the flat path of the
# quantizer returns the spec byte unchanged), so the blits sit
# seamlessly on the procedural background.

def quantize8(rgb):
    q = np.clip(rgb, 0, 255)
    r7 = np.round(q[..., 0] / 255.0 * 7).astype(np.uint8)
    g7 = np.round(q[..., 1] / 255.0 * 7).astype(np.uint8)
    b3 = np.round(q[..., 2] / 255.0 * 3).astype(np.uint8)
    return (g7 << 5) | (r7 << 2) | b3


def quantize8_fsdisc(rgb, cover):
    """GRB332 quantization with Floyd-Steinberg error diffusion
    inside the cover region (planet disc + glow) only. Pixels
    outside cover keep the flat quantize8() byte and propagate no
    error, so the backdrop part stays byte-identical to the flat
    data and the blit seam is preserved."""
    flat = quantize8(rgb)
    img = np.clip(rgb.astype(np.float32), 0, 255)
    h, w, _ = img.shape
    out = np.zeros((h, w), np.uint8)

    def lvl(v, n):
        return np.clip(np.round(v / 255.0 * (n - 1)), 0, n - 1)

    for y in range(h):
        for x in range(w):
            if not cover[y, x]:
                out[y, x] = flat[y, x]
                continue
            r, g, b = img[y, x]
            r7, g7, b3 = lvl(r, 8), lvl(g, 8), lvl(b, 4)
            out[y, x] = (int(g7) << 5) | (int(r7) << 2) | int(b3)
            pr = np.array([r7 * 255 / 7, g7 * 255 / 7, b3 * 255 / 3])
            err = img[y, x] - pr
            if x + 1 < w:
                img[y, x + 1] += err * 7 / 16
            if y + 1 < h:
                if x > 0:
                    img[y + 1, x - 1] += err * 3 / 16
                img[y + 1, x] += err * 5 / 16
                if x + 1 < w:
                    img[y + 1, x + 1] += err * 1 / 16
    return out


def grb8_expand(b):
    r = (b >> 2) & 7
    g = (b >> 5) & 7
    bl = b & 3
    return np.stack([r * 255.0 / 7, g * 255.0 / 7, bl * 255.0 / 3],
                    axis=-1)


def backdrop_df_rgb(w, h, x0, y0):
    """The Deep Field background (candidate A, SCR8) as RGB float,
    for the SCREEN 8 Earth rects: the GRB332 byte the SCR8
    draw_slice() paints at screen (x0+xx, y0+yy), expanded back to
    RGB so the fsdisc quantizer's flat path returns exactly that
    byte. The spec lives in tools/gen_deepfield.py (single
    source); it has no stars - the blit covers the slice stars
    under the rect anyway."""
    import gen_deepfield as DF
    img = np.zeros((h, w, 3), np.float32)
    for yy in range(h):
        for xx in range(w):
            b = DF.bg_byte(x0 + xx, y0 + yy)
            img[yy, xx] = (((b >> 2) & 7) * 255.0 / 7,
                           ((b >> 5) & 7) * 255.0 / 7,
                           (b & 3) * 255.0 / 3)
    return img


def write_planets8():
    import os
    os.makedirs("data", exist_ok=True)
    specs = (("TPL", 32, 78, 192, 106, 96, 90, 85, 600, 17),
             ("GPL", 142, 100, 114, 84, 66, 62, 56, 0, 23))
    for name, x0, y0, w, h, ccx, ccy, r, wx0, seed in specs:
        base = backdrop_df_rgb(w, h, x0, y0)
        rgb, cover = earth_rgb(w, h, ccx, ccy, r, seed)
        comp = np.where(cover[..., None], rgb, base)
        b8 = quantize8_fsdisc(comp, cover)
        out = bytearray()
        for yy in range(h):
            out += bytes(packbits_row([int(v) for v in b8[yy]]))
        path = f"data/{name.lower()}8.dat"
        with open(path, "wb") as f:
            f.write(out)
        print(f"{name}8 {w}x{h} packed={len(out)} "
              f"colours={len(np.unique(b8))} -> {path}")
        Image.fromarray(grb8_expand(b8).astype(np.uint8)).resize(
            (w * 2, h * 2), Image.NEAREST).save(
            f"design/planet_{name.lower()}8_preview.png")


if __name__ == "__main__":
    write_logo()
    write_planets8()
